"""Base classes and contracts for autonomous sandbox candidate models.

Every candidate model generated by the autonomous quant development branch
must inherit from BaseCandidateModel and produce discrete distributions
satisfying EvidenceGuard and mathematical invariants.
"""
from __future__ import annotations
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime, timezone
import math
from typing import Any, Dict, List, Optional, Tuple


@dataclass
class DiscreteDistribution:
    """Discrete two-team score probability distribution.
    
    Attributes:
        scores: Dict mapping (home_score, away_score) -> probability.
        home_expected: Mean projected points/goals for home side.
        away_expected: Mean projected points/goals for away side.
        p_home: Overall probability that home wins.
        p_away: Overall probability that away wins.
        p_draw: Overall probability of a regulation draw/tie.
    """
    scores: Dict[Tuple[int, int], float]
    home_expected: float
    away_expected: float
    p_home: float
    p_away: float
    p_draw: float = 0.0

    @classmethod
    def from_scores(cls, scores: Dict[Tuple[int, int], float]) -> DiscreteDistribution:
        """Constructs and normalizes distribution from score matrix."""
        total_p = sum(scores.values())
        if total_p <= 0.0:
            raise ValueError("Total probability mass must be strictly positive.")
        normalized = {k: v / total_p for k, v in scores.items()}

        h_exp = sum(h * p for (h, _), p in normalized.items())
        a_exp = sum(a * p for (_, a), p in normalized.items())
        p_h = sum(p for (h, a), p in normalized.items() if h > a)
        p_a = sum(p for (h, a), p in normalized.items() if a > h)
        p_d = sum(p for (h, a), p in normalized.items() if h == a)

        return cls(
            scores=normalized,
            home_expected=round(h_exp, 3),
            away_expected=round(a_exp, 3),
            p_home=max(0.01, min(0.99, round(p_h, 4))),
            p_away=max(0.01, min(0.99, round(p_a, 4))),
            p_draw=round(p_d, 4),
        )

    def total_prob(self, line: float, side: str = 'over') -> float:
        """Calculates discrete probability for total points/goals."""
        side = side.lower()
        if side in ('over', 'o'):
            p = sum(p for (h, a), p in self.scores.items() if (h + a) > line)
        elif side in ('under', 'u'):
            p = sum(p for (h, a), p in self.scores.items() if (h + a) < line)
        else:
            raise ValueError(f"Unknown total side: {side}")
        return max(0.01, min(0.99, round(p, 4)))

    def spread_prob(self, line: float, side: str = 'home') -> float:
        """Calculates discrete probability for handicap/spread.
        
        line is expressed relative to home (e.g. -3.5 means home must win by 4+).
        """
        side = side.lower()
        if side in ('home', '1', 'h'):
            p = sum(p for (h, a), p in self.scores.items() if (h - a + line) > 0)
        elif side in ('away', '2', 'a'):
            p = sum(p for (h, a), p in self.scores.items() if (a - h - line) > 0)
        else:
            raise ValueError(f"Unknown spread side: {side}")
        return max(0.01, min(0.99, round(p, 4)))

    def moneyline_prob(self, side: str = 'home') -> float:
        """Calculates moneyline win probability."""
        side = side.lower()
        if side in ('home', '1', 'h'):
            return self.p_home
        elif side in ('away', '2', 'a'):
            return self.p_away
        elif side in ('draw', 'tie', 'x'):
            return max(0.01, min(0.99, round(self.p_draw, 4)))
        else:
            raise ValueError(f"Unknown moneyline side: {side}")


class BaseCandidateModel(ABC):
    """Abstract base contract for any sandboxed machine learning or quantitative model."""

    def __init__(
        self,
        model_id: str,
        version: str,
        league: str,
        scope: str,
        family: str,
        required_features: Optional[List[str]] = None,
        metadata: Optional[Dict[str, Any]] = None,
    ):
        self.model_id = model_id
        self.version = version
        self.league = league
        self.scope = scope
        self.family = family
        self.required_features = required_features or []
        self.metadata = metadata or {}
        self.created_at = datetime.now(timezone.utc).isoformat()

    @abstractmethod
    def predict_distribution(self, game_context: Dict[str, Any]) -> DiscreteDistribution:
        """Generates the discrete score distribution for a game context.
        
        Must be strictly odds-independent (pure domain mechanics).
        Must execute in under 50ms.
        """
        pass

    def evaluate_market(
        self,
        market: str,
        selection: str,
        line: Optional[float],
        odds: float,
        game_context: Dict[str, Any],
    ) -> Tuple[float, float]:
        """Evaluates model win probability and mathematical expectation EV.
        
        Returns:
            (model_prob, ev) where ev = model_prob * odds - 1.0
        """
        dist = self.predict_distribution(game_context)
        m_lower = market.lower()
        sel_lower = selection.lower()

        if 'total' in m_lower or 'over' in sel_lower or 'under' in sel_lower:
            eff_line = float(line or 0.0)
            side = 'over' if 'over' in sel_lower else 'under'
            prob = dist.total_prob(eff_line, side=side)
        elif 'spread' in m_lower or 'handicap' in m_lower:
            eff_line = float(line or 0.0)
            side = 'home' if ('home' in sel_lower or '1' in sel_lower) else 'away'
            prob = dist.spread_prob(eff_line, side=side)
        else:
            if 'home' in sel_lower or '1' in sel_lower:
                prob = dist.moneyline_prob('home')
            elif 'away' in sel_lower or '2' in sel_lower:
                prob = dist.moneyline_prob('away')
            elif 'draw' in sel_lower or 'tie' in sel_lower or 'x' in sel_lower:
                prob = dist.moneyline_prob('draw')
            else:
                prob = dist.moneyline_prob('home')

        ev = round(prob * float(odds) - 1.0, 4)
        return prob, ev

    def to_dict(self) -> Dict[str, Any]:
        return {
            'model_id': self.model_id,
            'version': self.version,
            'league': self.league,
            'scope': self.scope,
            'family': self.family,
            'required_features': self.required_features,
            'created_at': self.created_at,
            'metadata': self.metadata,
        }
