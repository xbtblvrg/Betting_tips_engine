"""
Candidate model for NCAAM | quarter_3 | moneyline.

NCAAM plays two 20-minute halves, so "quarter_3" is a provider slice: roughly
the first 10 minutes of the second half. The model builds the exact discrete
margin distribution for that slice from possession-level scoring mechanics and
prices the 3-way outcome (home / tie / away). Tie mass is returned explicitly
so the engine can apply push or 3-way settlement.

Structure
---------
1. Segment geometry is read from the scope: start minute, length, and share of
   game points.
2. Team point expectations are adjusted for the matchup. Attack/defense is
   partially pooled, because the supplied expectations already embed it. Rest
   effects saturate.
3. Home edge is shrunk hierarchically toward a home-court prior scaled to the
   segment. The total is preserved, so only the gap is regularised.
4. The total possession count T is shared by both teams, which correlates
   their scoring. It is underdispersed (binomial) or overdispersed (negative
   binomial) according to its dispersion index. The team with the extra
   possession on odd T is unknown, so both cases are mixed with equal weight.
5. Each possession scores {0, 1, 2, 3} points. The per-possession law starts
   from a shot-mix template (field 2s, 3s, FT pairs, single FTs). The FT
   components are re-weighted by the expected fraction of the slice played in
   the bonus. Team fouls reset at halftime, and the bonus is reached through a
   Gamma(7, foul rate) arrival time. The law is then exponentially tilted
   (minimum-KL) so that its mean equals the team's points per possession.
6. Game-level shooting variance is a latent log-efficiency shock per team,
   integrated with Gauss-Hermite quadrature. This adds the extra between-game
   spread that pure per-possession randomness misses.
7. The exact margin PMF is the mixture over T and shocks of the
   cross-correlation of the two compound sums. Moneyline probabilities are
   P(D>0), P(D=0) and P(D<0).

All numeric settings below are structural domain priors, not output clamps.
Each can be overridden through constructor kwargs or game_context.
"""

import math
from typing import Any, Dict, Optional, Tuple

import numpy as np
from scipy import optimize, stats

from betting_engine.sandbox_models.base import BaseCandidateModel, DiscreteDistribution, build_universal_score_lattice

try:  # DiscreteDistribution is normally pre-loaded in the execution scope.
    from betting_engine.sandbox_models.base import BaseCandidateModel, DiscreteDistribution, build_universal_score_lattice
except Exception:  # pragma: no cover
    DiscreteDistribution = globals().get("DiscreteDistribution")  # type: ignore


class NCAAMQuarter3MoneylineModel(BaseCandidateModel):
    """Possession-compound margin model for the NCAAM 2nd-half opening slice."""

    # Structural priors. Every one can be overridden by kwargs or game_context.
    DEFAULT_PRIORS: Dict[str, float] = {
        # Segment geometry (minutes)
        "regulation_minutes": 40.0,
        "half_minutes": 20.0,
        "segment_start_minute": 20.0,      # quarter_3 = opening of 2nd half
        "segment_minutes": 10.0,
        # Empirical anchors for this segment (cold-start moments)
        "anchor_home_expected": 20.00,
        "anchor_away_expected": 18.75,
        # Possession process
        "possession_dispersion": 0.70,     # Var/Mean of total possessions in slice
        "segment_tempo_factor": 1.00,
        # Per-possession shot-mix template (NCAAM D-I typical)
        "q_zero": 0.48,
        "q_ft_single": 0.04,
        "q_field_two": 0.31,
        "q_ft_pair": 0.06,
        "q_three": 0.11,
        # Foul/bonus mechanics
        "team_fouls_per_half": 17.0,
        "bonus_foul_threshold": 7.0,
        "ft_bonus_share": 0.35,            # share of FT trips generated by bonus fouls
        # Latent game-level efficiency shock (log points per possession)
        "efficiency_shock_sd": 0.07,
        "quadrature_nodes": 7,
        # Matchup and rest
        "matchup_pooling": 0.35,           # partial pooling of attack/defense ratios
        "rating_reference": 100.0,         # used when ratings arrive on a 100 scale
        "rest_effect": 0.012,              # max log-efficiency gain from rest edge
        "rest_scale_days": 2.0,
        # Home-court hierarchy (full-game units, scaled by segment share)
        "hca_full_game": 3.0,
        "gap_prior_sd_full": 9.0,          # between-game true gap dispersion
        "gap_obs_sd_full": 4.0,            # noise in supplied expectations
        # Numerical support
        "support_sd_multiple": 9.0,
    }

    def __init__(
        self,
        model_id: str = "codex_synth_ncaam_quarter_3_1107_193355",
        version: str = "1.0.0",
        league: str = "NCAAM",
        scope: str = "quarter_3",
        family: str = "moneyline",
        **overrides: Any,
    ) -> None:
        try:
            super().__init__(
                model_id=model_id, version=version, league=league,
                scope=scope, family=family,
            )
        except TypeError:
            super().__init__(model_id, version, league, scope, family)
        self.model_id = model_id
        self.version = version
        self.league = league
        self.scope = scope
        self.family = family
        self.priors: Dict[str, float] = dict(self.DEFAULT_PRIORS)
        for k, v in overrides.items():
            if k in self.priors:
                self.priors[k] = float(v)
        self.last_diagnostics: Dict[str, Any] = {}

    # ------------------------------------------------------------------ #
    # Context helpers
    # ------------------------------------------------------------------ #
    @staticmethod
    def _as_float(x: Any) -> Optional[float]:
        try:
            v = float(x)
            return v if math.isfinite(v) else None
        except (TypeError, ValueError):
            return None

    def _get(self, ctx: Dict[str, Any], *paths: str) -> Optional[float]:
        """Return the first numeric value found among dotted paths."""
        for path in paths:
            node: Any = ctx
            ok = True
            for part in path.split("."):
                if isinstance(node, dict) and part in node:
                    node = node[part]
                else:
                    ok = False
                    break
            if ok:
                v = self._as_float(node)
                if v is not None:
                    return v
        return None

    def _param(self, ctx: Dict[str, Any], name: str) -> float:
        v = self._get(ctx, name, f"model_params.{name}")
        return v if v is not None else self.priors[name]

    def _ratio(self, value: Optional[float], ctx: Dict[str, Any]) -> float:
        """Map a rating to a multiplicative ratio around 1.

        Ratings may arrive as ratios (~1.0) or on a 100 scale.
        """
        if value is None or value <= 0.0:
            return 1.0
        ref = self._param(ctx, "rating_reference")
        return value / ref if value > 5.0 else value

    # ------------------------------------------------------------------ #
    # Mechanics primitives
    # ------------------------------------------------------------------ #
    def _bonus_time_fraction(self, ctx: Dict[str, Any], start: float, length: float) -> float:
        """Expected fraction of [start, start+length] played in the bonus.

        Fouls reset at each half. Fouls arrive as a Poisson process, so the
        bonus begins at T ~ Gamma(k, rate) after the half starts.
        """
        half = self._param(ctx, "half_minutes")
        rate = self._param(ctx, "team_fouls_per_half") / half
        k = self._param(ctx, "bonus_foul_threshold")
        a = start % half
        b = a + length

        def integral_in_bonus(t: float) -> float:
            # E[max(0, t - T)] = t*F_k(t) - (k/rate)*F_{k+1}(t)
            return t * stats.gamma.cdf(t, k, scale=1.0 / rate) - (k / rate) * stats.gamma.cdf(
                t, k + 1.0, scale=1.0 / rate
            )

        return (integral_in_bonus(b) - integral_in_bonus(a)) / length

    def _possession_template(self, ctx: Dict[str, Any], ft_multiplier: float) -> np.ndarray:
        q0 = self._param(ctx, "q_zero")
        q1 = self._param(ctx, "q_ft_single") * ft_multiplier
        q2 = self._param(ctx, "q_field_two") + self._param(ctx, "q_ft_pair") * ft_multiplier
        q3 = self._param(ctx, "q_three")
        # FT volume removed by the foul reset becomes empty possessions.
        removed = (1.0 - ft_multiplier) * (
            self._param(ctx, "q_ft_single") + self._param(ctx, "q_ft_pair")
        )
        q = np.array([q0 + removed, q1, q2, q3], dtype=float)
        q = np.maximum(q, 0.0)
        return q / q.sum()

    @staticmethod
    def _tilt(q: np.ndarray, target_mean: float) -> np.ndarray:
        """Minimum-KL exponential tilt of q to hit target_mean on {0, 1, 2, 3}."""
        ks = np.arange(q.size, dtype=float)
        top = ks[-1]
        # Numerical feasibility only: the mean of a law on {0..3} lies in (0, 3).
        tiny = 1e-9
        target = min(max(target_mean, tiny), top - tiny)
        logq = np.log(np.maximum(q, 1e-300))

        def mean_gap(theta: float) -> float:
            lw = logq + theta * ks
            lw -= lw.max()
            w = np.exp(lw)
            return float((w * ks).sum() / w.sum()) - target

        lo, hi = -5.0, 5.0
        while mean_gap(lo) > 0.0:
            lo *= 2.0
        while mean_gap(hi) < 0.0:
            hi *= 2.0
        theta = optimize.brentq(mean_gap, lo, hi, xtol=1e-12)
        lw = logq + theta * ks
        lw -= lw.max()
        p = np.exp(lw)
        return p / p.sum()

    def _possession_pmf(self, mean_t: float, dispersion: float, sd_mult: float) -> Tuple[np.ndarray, int]:
        """PMF of total possessions with mean mean_t and Var/Mean = dispersion."""
        var = dispersion * mean_t
        t_max = int(math.ceil(mean_t + sd_mult * math.sqrt(max(var, mean_t * 1e-3)) + 4))
        t = np.arange(t_max + 1)
        if abs(dispersion - 1.0) < 1e-6:
            pmf = stats.poisson.pmf(t, mean_t)
        elif dispersion < 1.0:
            n_trials = max(int(round(mean_t / (1.0 - dispersion))), int(math.ceil(mean_t)) + 1)
            pmf = stats.binom.pmf(t, n_trials, mean_t / n_trials)
        else:
            r = mean_t / (dispersion - 1.0)
            pmf = stats.nbinom.pmf(t, r, r / (r + mean_t))
        pmf = np.asarray(pmf, dtype=float)
        return pmf / pmf.sum(), t_max

    @staticmethod
    def _sum_pmfs(per_poss: np.ndarray, n_max: int) -> list:
        """List of PMFs of the sum of n i.i.d. possessions, n = 0..n_max."""
        out = [np.array([1.0])]
        cur = out[0]
        for _ in range(n_max):
            cur = np.convolve(cur, per_poss)
            out.append(cur)
        return out

    # ------------------------------------------------------------------ #
    # Situational expectation layer
    # ------------------------------------------------------------------ #
    def _segment_expectations(self, ctx: Dict[str, Any], seg_len: float) -> Dict[str, float]:
        mu_h = self._get(ctx, "home_expected", "home.expected")
        mu_a = self._get(ctx, "away_expected", "away.expected")
        mu_h = mu_h if mu_h is not None and mu_h > 0 else self._param(ctx, "anchor_home_expected")
        mu_a = mu_a if mu_a is not None and mu_a > 0 else self._param(ctx, "anchor_away_expected")

        # Matchup layer. Defense is a "points allowed" ratio (>1 = leakier).
        lam = self._param(ctx, "matchup_pooling")
        h_att = self._ratio(self._get(ctx, "home.attack", "home_attack"), ctx)
        h_def = self._ratio(self._get(ctx, "home.defense", "home_defense"), ctx)
        a_att = self._ratio(self._get(ctx, "away.attack", "away_attack"), ctx)
        a_def = self._ratio(self._get(ctx, "away.defense", "away_defense"), ctx)
        log_h = lam * (math.log(h_att) + math.log(a_def))
        log_a = lam * (math.log(a_att) + math.log(h_def))

        # Rest layer: saturating, antisymmetric in the rest differential.
        rh = self._get(ctx, "home_rest_days", "home.rest_days")
        ra = self._get(ctx, "away_rest_days", "away.rest_days")
        if rh is not None and ra is not None:
            kappa = self._param(ctx, "rest_effect")
            s = self._param(ctx, "rest_scale_days")
            edge = math.tanh((rh - ra) / s)
            log_h += 0.5 * kappa * edge
            log_a -= 0.5 * kappa * edge

        mu_h *= math.exp(log_h)
        mu_a *= math.exp(log_a)

        # Hierarchical shrinkage of the gap toward the segment home-court prior.
        total = mu_h + mu_a
        full_total = self._get(ctx, "full_game_total", "game_total", "expected_total")
        if full_total is not None and full_total > total:
            share = total / full_total
        else:
            share = seg_len / self._param(ctx, "regulation_minutes")

        neutral = bool(
            ctx.get("neutral_site")
            or (isinstance(ctx.get("venue"), dict) and ctx["venue"].get("neutral"))
        )
        hca_seg = 0.0 if neutral else self._param(ctx, "hca_full_game") * share
        tau = self._param(ctx, "gap_prior_sd_full") * share
        sig = self._param(ctx, "gap_obs_sd_full") * share
        w = tau * tau / (tau * tau + sig * sig)
        gap_obs = mu_h - mu_a
        gap_post = hca_seg + w * (gap_obs - hca_seg)

        return {
            "mu_home": 0.5 * (total + gap_post),
            "mu_away": 0.5 * (total - gap_post),
            "total": total,
            "gap_observed": gap_obs,
            "gap_posterior": gap_post,
            "hca_segment": hca_seg,
            "shrink_weight": w,
            "segment_share": share,
        }

    # ------------------------------------------------------------------ #
    # Core prediction
    # ------------------------------------------------------------------ #
    def margin_distribution(self, game_context: Dict[str, Any]) -> Tuple[np.ndarray, int, Dict[str, Any]]:
        ctx = game_context or {}
        seg_start = self._param(ctx, "segment_start_minute")
        seg_len = self._param(ctx, "segment_minutes")

        exp_ = self._segment_expectations(ctx, seg_len)

        # Foul-reset adjustment to free-throw volume.
        half = self._param(ctx, "half_minutes")
        bonus_seg = self._bonus_time_fraction(ctx, seg_start, seg_len)
        bonus_half = self._bonus_time_fraction(ctx, 0.0, half)
        b_share = self._param(ctx, "ft_bonus_share")
        ft_mult = (1.0 - b_share) + b_share * (bonus_seg / bonus_half if bonus_half > 0 else 1.0)
        q = self._possession_template(ctx, ft_mult)
        league_ppp = float((q * np.arange(4)).sum())

        # Possessions per team in the slice.
        pace = self._get(ctx, "pace", "tempo", "expected_possessions")
        if pace is None:
            hp = self._get(ctx, "home_pace", "home.pace", "home.tempo")
            ap = self._get(ctx, "away_pace", "away.pace", "away.tempo")
            if hp is not None and ap is not None:
                pace = 0.5 * (hp + ap)
        tempo_adj = self._param(ctx, "segment_tempo_factor")
        if pace is not None and pace > 0:
            mu_n = pace * (seg_len / self._param(ctx, "regulation_minutes")) * tempo_adj
        else:
            mu_n = exp_["total"] / (2.0 * league_ppp) * tempo_adj

        ppp_h = exp_["mu_home"] / mu_n
        ppp_a = exp_["mu_away"] / mu_n

        # Latent efficiency shocks (mean-preserving lognormal) via Gauss-Hermite.
        sd = self._param(ctx, "efficiency_shock_sd")
        n_nodes = int(self._param(ctx, "quadrature_nodes"))
        z, wq = np.polynomial.hermite_e.hermegauss(n_nodes)
        wq = wq / wq.sum()
        shocks = np.exp(sd * z - 0.5 * sd * sd)

        disp = self._param(ctx, "possession_dispersion")
        t_pmf, t_max = self._possession_pmf(
            2.0 * mu_n, disp, self._param(ctx, "support_sd_multiple")
        )
        n_max = (t_max + 1) // 2

        def mixed_sum_pmfs(ppp: float) -> list:
            mix = [np.zeros(3 * n + 1) for n in range(n_max + 1)]
            for s, w in zip(shocks, wq):
                per = self._tilt(q, ppp * s)
                for n, pm in enumerate(self._sum_pmfs(per, n_max)):
                    mix[n] += w * pm
            return mix

        H = mixed_sum_pmfs(ppp_h)
        A = mixed_sum_pmfs(ppp_a)

        offset = 3 * n_max
        margin = np.zeros(6 * n_max + 1)

        def add(nh: int, na: int, weight: float) -> None:
            # Index j of the correlation corresponds to margin d = j - 3*na.
            c = np.convolve(H[nh], A[na][::-1])
            start = offset - 3 * na
            margin[start:start + c.size] += weight * c

        for t, wt in enumerate(t_pmf):
            if wt <= 0.0:
                continue
            if t % 2 == 0:
                add(t // 2, t // 2, wt)
            else:
                hi, lo = (t + 1) // 2, (t - 1) // 2
                add(hi, lo, 0.5 * wt)
                add(lo, hi, 0.5 * wt)

        margin = np.maximum(margin, 0.0)
        margin /= margin.sum()

        d = np.arange(-offset, offset + 1)
        mean_d = float((d * margin).sum())
        var_d = float(((d - mean_d) ** 2 * margin).sum())
        diag = dict(exp_)
        diag.update({
            "possessions_per_team": mu_n,
            "ppp_home": ppp_h,
            "ppp_away": ppp_a,
            "league_ppp_template": league_ppp,
            "ft_multiplier": ft_mult,
            "bonus_fraction_segment": bonus_seg,
            "margin_mean": mean_d,
            "margin_sd": math.sqrt(var_d),
        })
        return margin, offset, diag

    def predict_distribution(self, game_context: Dict[str, Any]) -> "DiscreteDistribution":
        margin, offset, diag = self.margin_distribution(game_context)
        p_away = float(margin[:offset].sum())
        p_draw = float(margin[offset])
        p_home = float(margin[offset + 1:].sum())
        s = p_home + p_draw + p_away
        p_home, p_draw, p_away = p_home / s, p_draw / s, p_away / s

        diag.update({"p_home": p_home, "p_draw": p_draw, "p_away": p_away})
        self.last_diagnostics = diag

        dist_cls = DiscreteDistribution or globals().get("DiscreteDistribution")
        if hasattr(dist_cls, "from_probabilities"):
            try:
                return dist_cls.from_probabilities(p_home, p_draw, p_away)
            except Exception:
                pass
        return dist_cls(probabilities={"home": p_home, "draw": p_draw, "away": p_away})