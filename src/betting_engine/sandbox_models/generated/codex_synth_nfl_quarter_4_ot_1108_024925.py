class NFLQuarter4OTWinnerTotalModel(BaseCandidateModel):
    """
    Independent joint score model for NFL fourth-quarter-plus-overtime markets.

    Identification
    --------------
    Two means and an assumed variance/mean ratio do not identify touchdown,
    possession, overtime, or dependence dynamics. This model therefore uses
    maximum-entropy marginal score distributions subject to those moments,
    and independence in the absence of identified cross-team dependence.

    Each marginal has the form

        P(S=s) = exp(a*s + b*s**2) / Z,  s in the scoring support,

    with coefficients determined by its specified mean and variance. The
    infinite-support solution requires b < 0, or b == 0 with a < 0.

    The ordinary NFL scoring lattice is generated by 2-, 3-, 6-, 7-, and
    8-point scoring sequences. Its reachable totals are zero and integers
    greater than one. Set allow_one_point_score=True when the settlement
    window can isolate a one-point safety or another one-point outcome.

    Numerical truncation expands until a bound on omitted probability,
    first moment, and second moment meets numerical_tolerance. No betting
    line, odds, or bookmaker probability enters the forecast.

    Input contract
    --------------
    home_expected / away_expected:
        Expected FINAL points in this exact settlement window. If omitted,
        the supplied cold-start means 6.12 and 5.38 apply.

    Situational multipliers:
        Optional side-specific exposure_multiplier, attack_multiplier,
        defense_concession_multiplier and rest_multiplier, either inside
        game_context["home"/"away"] or prefixed with "home_"/"away_".
        All are positive ratios relative to the expectation baseline.
        Opponent defense_concession_multiplier modifies the scoring side.

    pace_multiplier / weather_multiplier / venue_multiplier:
        Optional positive, independently estimated scoring-rate ratios.

    feature_log_rate_coefficients:
        Optional independently fitted mapping with coefficients for
        rest_days, wind_speed, temp and is_dome. Each active coefficient
        requires a corresponding entry in feature_reference_values.
        Rest is side-specific; outdoor weather effects are suppressed
        inside a dome. Raw attack/defense ratings are deliberately not
        assigned an undocumented scale.

    dispersion_index:
        Variance/mean target, defaulting to the supplied prior 1.0.
        home_dispersion_index and away_dispersion_index override it.

    Live use:
        Supply home_remaining_expected, away_remaining_expected,
        home_scope_score and away_scope_score together. These expectations
        must already incorporate remaining regulation and overtime rules.
        Situational multipliers then apply to remaining scoring.

    Supplied expectations must already account for relevant overtime
    exposure. A draw means equal scores in this settlement window; it is
    not automatically a full-game tie. Settlement, odds >= 1.40, refunds,
    commission and positive-EV selection belong to the pricing layer.

    This is an explicitly assumed cold-start model, not an empirically
    calibrated claim of profitability. The supplied ROI benchmarks cannot
    establish achievable performance without independent validation data.
    """

    BASELINE_HOME = 6.12
    BASELINE_AWAY = 5.38

    def __init__(
        self,
        model_id="codex_synth_nfl_quarter_4_ot_1108_024925",
        version="1.0.0",
        league="NFL",
        scope="quarter_4_ot",
        family="winner_total",
        *,
        numerical_tolerance: Optional[float] = None,
        max_score_support: int = 4096,
        max_joint_cells: int = 4_000_000,
    ):
        super().__init__(
            model_id=model_id,
            version=version,
            league=league,
            scope=scope,
            family=family,
        )
        if (league, scope, family) != ("NFL", "quarter_4_ot", "winner_total"):
            raise ValueError("This candidate supports only NFL|quarter_4_ot|winner_total.")

        self.numerical_tolerance = (
            math.sqrt(np.finfo(float).eps)
            if numerical_tolerance is None
            else self._number(numerical_tolerance, "numerical_tolerance")
        )
        if not 0.0 < self.numerical_tolerance < 1.0:
            raise ValueError("numerical_tolerance must lie strictly between zero and one.")

        self.max_score_support = self._integer(
            max_score_support, "max_score_support", minimum=2
        )
        self.max_joint_cells = self._integer(
            max_joint_cells, "max_joint_cells", minimum=1
        )

    @staticmethod
    def _number(value: Any, name: str) -> float:
        if isinstance(value, (bool, np.bool_)):
            raise ValueError(f"{name} must be numeric, not boolean.")
        try:
            result = float(value)
        except (TypeError, ValueError, OverflowError) as exc:
            raise ValueError(f"{name} must be a finite number.") from exc
        if not math.isfinite(result):
            raise ValueError(f"{name} must be finite.")
        return result

    @classmethod
    def _integer(cls, value: Any, name: str, minimum: int = 0) -> int:
        number = cls._number(value, name)
        if number != math.floor(number) or number < minimum:
            raise ValueError(f"{name} must be an integer >= {minimum}.")
        return int(number)

    @classmethod
    def _positive(cls, value: Any, name: str) -> float:
        number = cls._number(value, name)
        if number <= 0.0:
            raise ValueError(f"{name} must be positive.")
        return number

    @staticmethod
    def _mapping(value: Any, name: str) -> Dict[str, Any]:
        if not isinstance(value, dict):
            raise ValueError(f"{name} must be a dictionary.")
        return value

    def _side_multiplier(self, context: Dict[str, Any], side: str, key: str) -> float:
        nested = self._mapping(context.get(side, {}), side)
        value = context.get(f"{side}_{key}", nested.get(key, 1.0))
        return self._positive(value, f"{side}_{key}")

    def _adjusted_mean(
        self, context: Dict[str, Any], side: str, baseline: float
    ) -> float:
        mean = self._number(baseline, f"{side}_expected")
        if mean < 0.0:
            raise ValueError(f"{side}_expected cannot be negative.")

        opponent = "away" if side == "home" else "home"
        multipliers = [
            self._side_multiplier(context, side, "exposure_multiplier"),
            self._side_multiplier(context, side, "attack_multiplier"),
            self._side_multiplier(context, opponent, "defense_concession_multiplier"),
            self._side_multiplier(context, side, "rest_multiplier"),
        ]
        for key in ("pace_multiplier", "weather_multiplier", "venue_multiplier"):
            multipliers.append(self._positive(context.get(key, 1.0), key))

        log_adjustment = math.fsum(math.log(value) for value in multipliers)
        coefficients = self._mapping(
            context.get("feature_log_rate_coefficients", {}),
            "feature_log_rate_coefficients",
        )
        references = self._mapping(
            context.get("feature_reference_values", {}),
            "feature_reference_values",
        )
        weather = self._mapping(context.get("weather", {}), "weather")
        supported = {"rest_days", "wind_speed", "temp", "is_dome"}
        if set(coefficients) - supported:
            raise ValueError("Unsupported feature_log_rate_coefficients key.")

        for feature, raw_coefficient in coefficients.items():
            coefficient = self._number(raw_coefficient, f"coefficient[{feature}]")
            if coefficient == 0.0:
                continue
            if feature not in references:
                raise ValueError(f"A reference value is required for {feature}.")
            reference = self._number(references[feature], f"reference[{feature}]")

            if feature == "rest_days":
                key = f"{side}_rest_days"
                if key not in context:
                    raise ValueError(f"{key} is required by its active coefficient.")
                value = self._number(context[key], key)
                if value < 0.0:
                    raise ValueError(f"{key} cannot be negative.")
            elif feature == "is_dome":
                if "is_dome" not in weather or not isinstance(weather["is_dome"], bool):
                    raise ValueError("weather.is_dome must be a boolean.")
                value = float(weather["is_dome"])
            else:
                if "is_dome" not in weather or not isinstance(weather["is_dome"], bool):
                    raise ValueError("Weather effects require boolean weather.is_dome.")
                if weather["is_dome"]:
                    continue
                if feature not in weather:
                    raise ValueError(f"weather.{feature} is required.")
                value = self._number(weather[feature], f"weather.{feature}")
                if feature == "wind_speed" and value < 0.0:
                    raise ValueError("wind_speed cannot be negative.")

            log_adjustment += coefficient * (value - reference)

        if not math.isfinite(log_adjustment):
            raise ValueError("Non-finite situational adjustment.")
        if mean == 0.0:
            return 0.0
        try:
            result = math.exp(math.log(mean) + log_adjustment)
        except OverflowError as exc:
            raise ValueError("Adjusted expectation overflowed.") from exc
        if not math.isfinite(result) or result <= 0.0:
            raise ValueError("Adjusted expectation is numerically unrepresentable.")
        return result

    def _marginal(
        self, mean: float, dispersion: float, allow_one: bool
    ) -> Tuple[np.ndarray, np.ndarray]:
        if mean == 0.0:
            return np.array([0], dtype=int), np.array([1.0])

        variance = mean * dispersion
        if not math.isfinite(variance):
            raise ValueError("Requested variance overflowed.")

        if not allow_one and mean < 2.0:
            lower, upper = 0, 2
        else:
            lower = math.floor(mean)
            upper = lower if mean == lower else lower + 1

        minimum_variance = (mean - lower) * (upper - mean)
        if variance < minimum_variance:
            raise ValueError(
                "The requested variance is impossible on the scoring lattice. "
                "Supply a supported dispersion estimate; it is not silently clamped."
            )
        if variance == minimum_variance:
            if lower == upper:
                return np.array([lower]), np.array([1.0])
            upper_probability = (mean - lower) / (upper - lower)
            return (
                np.array([lower, upper]),
                np.array([1.0 - upper_probability, upper_probability]),
            )

        tolerance = self.numerical_tolerance
        second_moment = mean * mean + variance
        if not math.isfinite(second_moment):
            raise ValueError("Requested second moment overflowed.")

        scale = max(1.0, mean, math.sqrt(variance))
        target = np.array([mean / scale, second_moment / (scale * scale)])
        normalization = np.maximum(1.0, np.abs(target))

        # Numerical initialization only; final coefficients solve the moments.
        theta = np.array(
            [mean * scale / variance, -(scale * scale) / (2.0 * variance)]
        )
        support_end = max(2, math.ceil(mean + math.sqrt(variance)))

        while support_end <= self.max_score_support:
            scores = np.arange(support_end + 1, dtype=int)
            if not allow_one:
                scores = scores[scores != 1]
            scaled = scores.astype(float) / scale
            features = np.column_stack((scaled, scaled * scaled))

            def evaluate(parameters):
                logits = features @ parameters
                log_z = logsumexp(logits)
                probabilities = np.exp(logits - log_z)
                moments = probabilities @ features
                return probabilities, moments, float(log_z)

            def residual(parameters):
                _, moments, _ = evaluate(parameters)
                return (moments - target) / normalization

            def jacobian(parameters):
                probabilities, moments, _ = evaluate(parameters)
                centered = features - moments
                covariance = centered.T @ (probabilities[:, None] * centered)
                return covariance / normalization[:, None]

            fit = least_squares(
                residual,
                theta,
                jac=jacobian,
                xtol=tolerance,
                ftol=tolerance,
                gtol=tolerance * tolerance,
            )
            theta = fit.x
            probabilities, _, log_z = evaluate(theta)
            moment_error = float(np.max(np.abs(residual(theta))))
            a = float(theta[0] / scale)
            b = float(theta[1] / (scale * scale))

            # Bound the omitted tail by a geometric series. For b <= 0,
            # successive mass ratios are nonincreasing.
            integrable = b < 0.0 or (b == 0.0 and a < 0.0)
            tail_error = math.inf
            if integrable:
                first = support_end + 1
                log_ratio = a + b * (2 * first + 1)
                if log_ratio < 0.0:
                    denominator = -math.expm1(log_ratio)
                    ratio = math.exp(log_ratio)
                    log_first_mass = a * first + b * first * first - log_z
                    first_mass = math.exp(log_first_mass)
                    tail_mass = first_mass / denominator
                    tail_first = first_mass * (
                        first / denominator + ratio / denominator**2
                    )
                    tail_second = first_mass * (
                        first * first / denominator
                        + 2 * first * ratio / denominator**2
                        + ratio * (1 + ratio) / denominator**3
                    )
                    tail_error = max(
                        tail_mass,
                        tail_first / max(1.0, mean),
                        tail_second / max(1.0, second_moment),
                    )

            if fit.success and moment_error <= tolerance and tail_error <= tolerance:
                probabilities /= probabilities.sum()
                return scores, probabilities

            if support_end == self.max_score_support:
                break
            support_end = min(self.max_score_support, support_end * 2)

        raise ValueError(
            "No converged, normalizable maximum-entropy marginal within the "
            "numerical resource budget. The moments may require a different "
            "identified distribution family or a larger max_score_support."
        )

    def predict_distribution(self, game_context: Dict[str, Any]) -> DiscreteDistribution:
        context = self._mapping(game_context, "game_context")
        for key, expected in (
            ("league", "NFL"),
            ("scope", "quarter_4_ot"),
            ("family", "winner_total"),
        ):
            if key in context and context[key] != expected:
                raise ValueError(f"Unexpected {key}: {context[key]!r}.")

        live_keys = {
            "home_remaining_expected",
            "away_remaining_expected",
            "home_scope_score",
            "away_scope_score",
        }
        present = live_keys.intersection(context)
        if present and present != live_keys:
            raise ValueError("Live prediction requires all four remaining-score inputs.")

        allow_one = context.get("allow_one_point_score", False)
        if not isinstance(allow_one, bool):
            raise ValueError("allow_one_point_score must be boolean.")

        distributions = {}
        offsets = {}
        for side, baseline in (
            ("home", self.BASELINE_HOME),
            ("away", self.BASELINE_AWAY),
        ):
            expectation_key = (
                f"{side}_remaining_expected" if present else f"{side}_expected"
            )
            mean = self._adjusted_mean(
                context, side, context.get(expectation_key, baseline)
            )
            dispersion = self._positive(
                context.get(
                    f"{side}_dispersion_index",
                    context.get("dispersion_index", 1.0),
                ),
                f"{side}_dispersion_index",
            )
            distributions[side] = self._marginal(mean, dispersion, allow_one)
            offsets[side] = (
                self._integer(context[f"{side}_scope_score"], f"{side}_scope_score")
                if present
                else 0
            )

        home_scores, home_probabilities = distributions["home"]
        away_scores, away_probabilities = distributions["away"]
        if len(home_scores) * len(away_scores) > self.max_joint_cells:
            raise ValueError("Joint distribution exceeds max_joint_cells.")

        # Tuple-keyed score mass preserves winner/total dependence exactly:
        # both contract legs must be priced from the same score realization.
        scores = {
            (
                int(home_score) + offsets["home"],
                int(away_score) + offsets["away"],
            ): float(home_probability * away_probability)
            for home_score, home_probability in zip(home_scores, home_probabilities)
            for away_score, away_probability in zip(away_scores, away_probabilities)
        }
        mass = math.fsum(scores.values())
        if not math.isfinite(mass) or mass <= 0.0:
            raise ArithmeticError("Invalid joint probability mass.")
        scores = {score: probability / mass for score, probability in scores.items()}
        return DiscreteDistribution.from_scores(scores)