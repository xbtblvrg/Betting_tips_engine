class ATPSecondSetMarkovThreeWayModel(BaseCandidateModel):
    """
    ATP | period_2 | three_way

    Second-set game counts are generated by an exact Markov chain, not by Poisson
    counts:

      * Each player has a serve-point win probability p_H or p_A.
      * Point -> game: the closed-form hold function
            g(p) = p^4 [1 + 4q + 10q^2] + 20 p^3 q^3 * p^2 / (1 - 2pq),  q = 1 - p
      * Game -> set: an exact (i, j) lattice with alternating serve. Terminal states
        are 6-0..6-4, 7-5 and 7-6. A 6-6 tiebreak is solved by an exact point-level
        DP with the ABBA serve rotation and a closed-form win-by-two deuce tail.
      * The set-2 first server is inherited from set 1 when it is known. A set-1
        tiebreak counts as one game for rotation parity. If set 1 is unknown, the
        model mixes both orders with equal weight.
      * Fatigue is a per-game decay of each player's serve strength in logit space.
        The decay comes from the rest-day deficit, spread over the games played so
        far in the match. Only the differential between players enters.
      * (p_H, p_A) are solved numerically so the chain's E[G_H] and E[G_A] match the
        situational targets. The targets start from the empirical anchors
        (5.76 / 5.31) and are scaled multiplicatively by serve/return exposure and
        surface pace.
      * There is no venue-advantage constant. Any home asymmetry comes only from
        the solved serve-strength gap.

    The three-way legs are priced from the exact joint P(G_H = i, G_A = j) on the
    handicapped game margin M = G_H - G_A + h:
        home: M > 0, draw: M == 0, away: M < 0.
    The handicap h is read from the context. With an integer h, the draw leg
    carries the true lumpy lattice mass. With h = 0, the draw leg is structurally
    zero, because a set cannot be drawn.
    """

    # Empirical domain anchors for this segment (observed baseline means).
    ANCHOR_HOME = 5.76
    ANCHOR_AWAY = 5.31

    def __init__(
        self,
        model_id: str = "codex_synth_atp_period_2_1107_154151",
        version: str = "1.0.0",
        league: str = "ATP",
        scope: str = "period_2",
        family: str = "three_way",
    ) -> None:
        super().__init__(
            model_id=model_id,
            version=version,
            league=league,
            scope=scope,
            family=family,
        )
        # Bounds on the serve logits. These come from float precision, not from any
        # modelling choice: past them, expit() saturates to exactly 0 or 1.
        self._logit_bound = -math.log(np.finfo(float).eps)
        self.last_diagnostics: Dict[str, Any] = {}

    # ------------------------------------------------------------------ #
    # Context helpers
    # ------------------------------------------------------------------ #
    @staticmethod
    def _num(value: Any) -> Optional[float]:
        try:
            if value is None:
                return None
            v = float(value)
            return v if math.isfinite(v) else None
        except (TypeError, ValueError):
            return None

    def _get(self, ctx: Dict[str, Any], *keys: str) -> Optional[float]:
        for k in keys:
            if k in ctx:
                v = self._num(ctx.get(k))
                if v is not None:
                    return v
        return None

    def _rating(self, ctx: Dict[str, Any], side: str, kind: str) -> Optional[float]:
        nested = ctx.get(side)
        if isinstance(nested, dict):
            v = self._num(nested.get(kind))
            if v is not None:
                return v
        return self._get(ctx, f"{side}_{kind}", f"{side}_{kind}_rating")

    # ------------------------------------------------------------------ #
    # Point -> game -> tiebreak -> set primitives
    # ------------------------------------------------------------------ #
    @staticmethod
    def _hold(p: float) -> float:
        q = 1.0 - p
        deuce_den = 1.0 - 2.0 * p * q
        return p ** 4 * (1.0 + 4.0 * q + 10.0 * q * q) + 20.0 * p ** 3 * q ** 3 * p * p / deuce_den

    @staticmethod
    def _tiebreak(pa: float, pb: float) -> float:
        """P(A wins tiebreak) when A serves the first point (ABBA rotation)."""
        P = np.zeros((7, 7))
        P[0, 0] = 1.0
        win_a = 0.0
        for n in range(12):
            server_a = (n == 0) or (((n + 1) // 2) % 2 == 0)
            pw = pa if server_a else 1.0 - pb
            for a in range(0, min(n, 6) + 1):
                b = n - a
                if b < 0 or b > 6:
                    continue
                pr = P[a, b]
                if pr == 0.0:
                    continue
                if a + 1 == 7:
                    win_a += pr * pw
                else:
                    P[a + 1, b] += pr * pw
                if b + 1 < 7:
                    P[a, b + 1] += pr * (1.0 - pw)
        # 6-6 onward: each pair of points has one serve per player.
        x = pa * (1.0 - pb)
        y = (1.0 - pa) * pb
        den = x + y
        tail = x / den if den > 0.0 else 0.5
        return win_a + P[6, 6] * tail

    @staticmethod
    def _terminal(i: int, j: int) -> bool:
        if i == 7 or j == 7:
            return True
        return (i >= 6 or j >= 6) and abs(i - j) >= 2

    def _set_joint(
        self,
        x_h: float,
        x_a: float,
        home_first: bool,
        d_h: float,
        d_a: float,
        offset: float,
    ) -> np.ndarray:
        """Exact joint matrix J[i, j] = P(G_H = i, G_A = j) for a single set."""
        J = np.zeros((8, 8))
        S = np.zeros((7, 7))
        S[0, 0] = 1.0
        for k in range(12):
            home_serves = (k % 2 == 0) == home_first
            t = offset + k
            if home_serves:
                pw = self._hold(float(expit(x_h - d_h * t)))
            else:
                pw = 1.0 - self._hold(float(expit(x_a - d_a * t)))
            for i in range(max(0, k - 6), min(k, 6) + 1):
                j = k - i
                pr = S[i, j]
                if pr == 0.0:
                    continue
                for ni, nj, pp in ((i + 1, j, pw), (i, j + 1, 1.0 - pw)):
                    if self._terminal(ni, nj):
                        J[ni, nj] += pr * pp
                    else:
                        S[ni, nj] += pr * pp
        # 6-6 tiebreak. The first server is the server of game index 12, i.e. the
        # player who served first in the set.
        pr = S[6, 6]
        if pr > 0.0:
            t = offset + 12
            ph = float(expit(x_h - d_h * t))
            pa = float(expit(x_a - d_a * t))
            w_home = self._tiebreak(ph, pa) if home_first else 1.0 - self._tiebreak(pa, ph)
            J[7, 6] += pr * w_home
            J[6, 7] += pr * (1.0 - w_home)
        return J

    def _mixed_joint(self, x_h, x_a, w_home_first, d_h, d_a, offset) -> np.ndarray:
        J = np.zeros((8, 8))
        if w_home_first > 0.0:
            J += w_home_first * self._set_joint(x_h, x_a, True, d_h, d_a, offset)
        if w_home_first < 1.0:
            J += (1.0 - w_home_first) * self._set_joint(x_h, x_a, False, d_h, d_a, offset)
        return J

    # ------------------------------------------------------------------ #
    # Situational targets
    # ------------------------------------------------------------------ #
    def _targets(self, ctx: Dict[str, Any]) -> Tuple[float, float]:
        t_h = self._get(ctx, "home_expected") or self.ANCHOR_HOME
        t_a = self._get(ctx, "away_expected") or self.ANCHOR_AWAY

        # Serve/return exposure: home serve vs away return, against the reverse.
        # The share shifts symmetrically, so the product of the targets is preserved.
        att_h = self._rating(ctx, "home", "attack")
        def_h = self._rating(ctx, "home", "defense")
        att_a = self._rating(ctx, "away", "attack")
        def_a = self._rating(ctx, "away", "defense")
        if all(v is not None and v > 0 for v in (att_h, def_h, att_a, def_a)):
            r = (att_h / def_a) / (att_a / def_h)
            t_h *= math.sqrt(r)
            t_a /= math.sqrt(r)

        # Surface pace / tempo: faster conditions mean higher hold rates and longer
        # sets. This scales total set length.
        pace = self._get(ctx, "surface_pace", "pace", "tempo", "pace_index")
        if pace is not None and pace > 0:
            t_h *= pace
            t_a *= pace
        return t_h, t_a

    def _fatigue(self, ctx: Dict[str, Any], offset: float) -> Tuple[float, float]:
        r_h = self._get(ctx, "home_rest_days")
        r_a = self._get(ctx, "away_rest_days")
        if r_h is None or r_a is None:
            return 0.0, 0.0
        horizon = offset + 13.0  # games in the match through the latest set-2 game
        f_h = math.log1p(1.0 / (1.0 + max(r_h, 0.0))) / horizon
        f_a = math.log1p(1.0 / (1.0 + max(r_a, 0.0))) / horizon
        base = min(f_h, f_a)  # only the differential fatigue enters
        return f_h - base, f_a - base

    def _first_server_weight(self, ctx: Dict[str, Any]) -> float:
        s2 = ctx.get("set2_first_server")
        if isinstance(s2, str):
            return 1.0 if s2.lower() == "home" else 0.0
        s1 = ctx.get("set1_first_server")
        g1 = self._get(ctx, "set1_games", "set1_total_games")
        if isinstance(s1, str) and g1 is not None:
            home_first_s1 = s1.lower() == "home"
            same = int(round(g1)) % 2 == 0
            return 1.0 if (home_first_s1 == same) else 0.0
        return 0.5

    # ------------------------------------------------------------------ #
    # Main entry point
    # ------------------------------------------------------------------ #
    def predict_distribution(self, game_context: Dict[str, Any]) -> "DiscreteDistribution":
        ctx = game_context or {}
        t_h, t_a = self._targets(ctx)

        offset = self._get(ctx, "set1_games", "set1_total_games")
        if offset is None:
            offset = self.ANCHOR_HOME + self.ANCHOR_AWAY
        d_h, d_a = self._fatigue(ctx, offset)
        w_first = self._first_server_weight(ctx)

        def residual(x: np.ndarray) -> np.ndarray:
            J = self._mixed_joint(x[0], x[1], w_first, d_h, d_a, offset)
            idx = np.arange(8)
            return np.array([J.sum(axis=1) @ idx - t_h, J.sum(axis=0) @ idx - t_a])

        # Initial guess: split serve strength by target share. Only the starting
        # point depends on this; the solver determines the final values.
        share = t_h / (t_h + t_a)
        x0 = np.array([logit(0.5 + 0.5 * share), logit(0.5 + 0.5 * (1.0 - share))])
        lb = self._logit_bound
        sol = least_squares(residual, x0, bounds=(-lb, lb), method="trf",
                            xtol=1e-12, ftol=1e-12, gtol=1e-12)
        x_h, x_a = float(sol.x[0]), float(sol.x[1])

        J = self._mixed_joint(x_h, x_a, w_first, d_h, d_a, offset)
        J /= J.sum()

        h = self._get(ctx, "handicap", "line", "spread", "home_handicap") or 0.0
        p_home = p_draw = p_away = 0.0
        for i in range(8):
            for j in range(8):
                m = J[i, j]
                if m == 0.0:
                    continue
                v = i - j + h
                if abs(v) < 1e-9:
                    p_draw += m
                elif v > 0:
                    p_home += m
                else:
                    p_away += m
        tot = p_home + p_draw + p_away
        p_home, p_draw, p_away = p_home / tot, p_draw / tot, p_away / tot

        idx = np.arange(8)
        self.last_diagnostics = {
            "p_serve_home": float(expit(x_h)),
            "p_serve_away": float(expit(x_a)),
            "hold_home": self._hold(float(expit(x_h))),
            "hold_away": self._hold(float(expit(x_a))),
            "target_home": t_h,
            "target_away": t_a,
            "fit_home": float(J.sum(axis=1) @ idx),
            "fit_away": float(J.sum(axis=0) @ idx),
            "home_first_weight": w_first,
            "handicap": h,
            "joint": J,
            "solver_cost": float(sol.cost),
        }

        try:
            return DiscreteDistribution(
                probabilities={"home": p_home, "draw": p_draw, "away": p_away}
            )
        except TypeError:
            return DiscreteDistribution.from_probabilities(p_home, p_draw, p_away)