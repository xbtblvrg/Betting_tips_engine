class WTADoubleChanceModel(BaseCandidateModel):
    """
    Cold-start, completed-match model for standard WTA singles.

    Construction
    ------------
    Enumerate legal best-of-three match outcomes, retaining the MATCH winner
    separately from games won. The player winning more games can lose a match.

    Let q(s) be a neutral reference measure generated by equally likely game
    winners, with equally likely tiebreak winners. Given expected games m,
    choose the distribution minimizing KL(p || q), subject to E_p[G] = m:

        p_theta(s) = q(s) exp(theta @ G(s) - log Z(theta)).

    The calibration gradient is E[G] - m and its Hessian is Cov(G).
    This preserves legal score support and fits both supplied moments without
    inventing serve statistics, home advantage, draw probability, or dispersion.

    This is an explicit maximum-relative-entropy cold-start assumption, NOT an
    identified point-level serve model. Two game-count moments alone do not
    establish serve strengths or out-of-sample calibration. No ROI or benchmark
    improvement is claimed.

    Settlement
    ----------
    Returned probabilities are conditional on a completed standard match:
        1X = home; X2 = away; 12 = home + away = 1.
    Voids are refunds, never draws. Retirement-sensitive contracts require a
    separate settlement model; they cannot be encoded by this three-state API.

    Situational inputs
    ------------------
    home_expected / away_expected: completed-match expected games.
    home_expected_scale / away_expected_scale: positive game-count multipliers.
    pace_scale: positive multiplier explicitly expressed in expected-game units.

    feature_coefficients optionally supplies externally fitted coefficients:
        attack, opponent_defense, rest_days, opponent_rest_days,
        wind_speed, temp, is_dome.

    Attack and defense are positive dimensionless indices with neutral value 1.
    Rest uses log1p(days). Weather uses its supplied units. Coefficients must
    therefore be trained using exactly these feature definitions. Missing
    features required by nonzero coefficients raise an error. Without fitted
    coefficients, raw contextual features do not receive invented effects.

    Scoring reference:
    https://www.itftennis.com/media/15607/wta-2026-rulebook.pdf
    """

    def __init__(
        self,
        model_id: str = "codex_synth_wta_full_game_1108_045407",
        version: str = "1.0.0",
        league: str = "WTA",
        scope: str = "full_game",
        family: str = "double_chance",
    ) -> None:
        super().__init__(
            model_id=model_id,
            version=version,
            league=league,
            scope=scope,
            family=family,
        )
        if (league, scope, family) != ("WTA", "full_game", "double_chance"):
            raise ValueError("This model supports WTA|full_game|double_chance only.")

    @staticmethod
    def _number(value: Any, name: str, *, positive: bool = False) -> float:
        if isinstance(value, (bool, np.bool_)):
            raise ValueError(f"{name} must be numeric, not boolean.")
        try:
            result = float(value)
        except (TypeError, ValueError, OverflowError) as exc:
            raise ValueError(f"{name} must be a finite number.") from exc
        if not math.isfinite(result) or (positive and result <= 0.0):
            raise ValueError(f"{name} must be finite"
                             + (" and positive." if positive else "."))
        return result

    @staticmethod
    @lru_cache(maxsize=None)
    def _set_outcomes(
        home: int = 0, away: int = 0
    ) -> Tuple[Tuple[int, int, float], ...]:
        if max(home, away) >= 6 and abs(home - away) >= 2:
            return ((home, away, 1.0),)

        # Under the neutral reference measure, both seven-point and ten-point
        # tiebreaks have equal winner probabilities and count as one game.
        half = 1.0 / 2.0
        if home == away == 6:
            return ((7, 6, half), (6, 7, half))

        outcomes = defaultdict(float)
        for next_home, next_away in ((home + 1, away), (home, away + 1)):
            for games_home, games_away, probability in (
                WTADoubleChanceModel._set_outcomes(next_home, next_away)
            ):
                outcomes[(games_home, games_away)] += half * probability
        return tuple((h, a, p) for (h, a), p in sorted(outcomes.items()))

    @staticmethod
    @lru_cache(maxsize=1)
    def _support() -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        active = {(0, 0, 0, 0): 1.0}
        finished = defaultdict(float)
        sets = WTADoubleChanceModel._set_outcomes()

        while active:
            following = defaultdict(float)
            for (sets_home, sets_away, games_home, games_away), mass in active.items():
                for h, a, probability in sets:
                    sh = sets_home + int(h > a)
                    sa = sets_away + int(a > h)
                    gh, ga = games_home + h, games_away + a
                    weight = mass * probability
                    if sh == 2 or sa == 2:
                        finished[(gh, ga, sh == 2)] += weight
                    else:
                        following[(sh, sa, gh, ga)] += weight
            active = following

        keys = sorted(finished)
        games = np.asarray([key[:2] for key in keys], dtype=float)
        home_wins = np.asarray([key[2] for key in keys], dtype=bool)
        reference = np.asarray([finished[key] for key in keys], dtype=float)
        reference /= reference.sum()
        log_reference = np.log(reference)
        hull = ConvexHull(np.unique(games, axis=0)).equations.copy()

        for array in (games, home_wins, log_reference, hull):
            array.setflags(write=False)
        return games, home_wins, log_reference, hull

    @classmethod
    def _feature(
        cls, context: Mapping[str, Any], side: str, name: str
    ) -> float:
        opponent = "away" if side == "home" else "home"

        if name in {"attack", "opponent_defense"}:
            owner = side if name == "attack" else opponent
            attribute = "attack" if name == "attack" else "defense"
            player = context.get(owner)
            if not isinstance(player, Mapping) or attribute not in player:
                raise ValueError(f"Missing {owner}.{attribute}.")
            return math.log(
                cls._number(player[attribute], f"{owner}.{attribute}", positive=True)
            )

        if name in {"rest_days", "opponent_rest_days"}:
            owner = side if name == "rest_days" else opponent
            key = f"{owner}_rest_days"
            if key not in context:
                raise ValueError(f"Missing {key}.")
            rest = cls._number(context[key], key)
            if rest < 0.0:
                raise ValueError(f"{key} cannot be negative.")
            return math.log1p(rest)

        weather = context.get("weather", {})
        if not isinstance(weather, Mapping):
            raise ValueError("weather must be a mapping.")
        if name not in weather and name not in context:
            raise ValueError(f"Missing weather feature {name}.")
        value = weather[name] if name in weather else context[name]
        if name == "is_dome":
            if not isinstance(value, (bool, np.bool_)):
                raise ValueError("is_dome must be boolean.")
            return float(value)
        return cls._number(value, name)

    @classmethod
    def _target(cls, context: Mapping[str, Any]) -> np.ndarray:
        coefficients = context.get("feature_coefficients", {})
        if not isinstance(coefficients, Mapping):
            raise ValueError("feature_coefficients must be a mapping.")

        allowed = {
            "attack", "opponent_defense", "rest_days", "opponent_rest_days",
            "wind_speed", "temp", "is_dome",
        }
        unknown = set(coefficients) - allowed
        if unknown:
            raise ValueError(f"Unsupported feature coefficients: {unknown!r}.")

        fitted = {
            name: cls._number(value, f"feature_coefficients.{name}")
            for name, value in coefficients.items()
        }
        pace = cls._number(context.get("pace_scale", 1.0), "pace_scale", positive=True)
        means = []

        for side, baseline in (("home", 12.80), ("away", 11.80)):
            expected = cls._number(
                context.get(f"{side}_expected", baseline),
                f"{side}_expected",
                positive=True,
            )
            scale = cls._number(
                context.get(f"{side}_expected_scale", 1.0),
                f"{side}_expected_scale",
                positive=True,
            )
            adjustment = math.fsum(
                coefficient * cls._feature(context, side, name)
                for name, coefficient in fitted.items()
                if coefficient != 0.0
            )
            log_mean = math.fsum(
                (math.log(expected), math.log(scale), math.log(pace), adjustment)
            )
            try:
                mean = math.exp(log_mean)
            except OverflowError as exc:
                raise ValueError("Situational adjustments overflow expected games.") from exc
            means.append(cls._number(mean, f"{side} adjusted expected games", positive=True))

        return np.asarray(means, dtype=float)

    @staticmethod
    def _validate_contract(context: Mapping[str, Any]) -> None:
        for key, expected in (
            ("league", "WTA"), ("scope", "full_game"), ("family", "double_chance")
        ):
            if key in context and context[key] != expected:
                raise ValueError(f"Unsupported {key}: {context[key]!r}.")

        if context.get("best_of", 3) != 3:
            raise ValueError("Only best-of-three matches are supported.")
        if context.get("match_format", "standard_singles") != "standard_singles":
            raise ValueError("Only standard singles with full deciding sets is supported.")
        if context.get("deciding_match_tiebreak", False):
            raise ValueError("A replacement match tiebreak requires different score support.")
        if context.get("advantage_final_set", False):
            raise ValueError("An advantage final set requires different score support.")
        if context.get("is_live", False):
            raise ValueError("Live matches require conditioning on the current score.")

        settlement = context.get("settlement_rule", "completed_match_only")
        if settlement not in {"completed_match_only", "void_on_noncompletion"}:
            raise ValueError(
                "Retirement-sensitive settlement needs a separate settlement model."
            )

    @classmethod
    def _fit(
        cls, context: Mapping[str, Any]
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        cls._validate_contract(context)
        target = cls._target(context)
        games, home_wins, log_reference, hull = cls._support()

        eps = np.finfo(float).eps
        tolerance = math.sqrt(eps)
        scale = np.maximum(1.0, np.abs(target))
        slack = hull[:, :-1] @ target + hull[:, -1]
        numerical_margin = eps * max(1.0, float(np.linalg.norm(target)))
        if np.any(slack >= -numerical_margin):
            raise ValueError(
                "Expected games must lie strictly inside the legal match-score "
                "moment region; targets are not silently clipped or projected."
            )

        def evaluate(theta: np.ndarray):
            log_weights = log_reference + games @ theta
            probabilities = np.exp(log_weights - logsumexp(log_weights))
            mean = probabilities @ games
            centered = games - mean
            covariance = (centered.T * probabilities) @ centered
            return probabilities, mean, covariance

        result = least_squares(
            fun=lambda theta: (evaluate(theta)[1] - target) / scale,
            x0=np.zeros(target.size, dtype=float),
            jac=lambda theta: evaluate(theta)[2] / scale[:, None],
            ftol=tolerance,
            xtol=tolerance,
            gtol=eps,
        )
        probabilities, mean, covariance = evaluate(result.x)
        if (
            not np.all(np.isfinite(probabilities))
            or not np.all(np.isfinite(covariance))
            or np.any(np.abs(mean - target) > tolerance * scale)
        ):
            raise ArithmeticError(
                f"Expected-game calibration failed: target={target.tolist()}, "
                f"achieved={mean.tolist()}, solver={result.message}"
            )

        probabilities /= probabilities.sum()
        return probabilities, mean, covariance, home_wins

    def predict_distribution(
        self, game_context: Dict[str, Any]
    ) -> DiscreteDistribution:
        probabilities, _, _, home_wins = self._fit(game_context)
        home = float(probabilities[home_wins].sum())
        away = float(probabilities[~home_wins].sum())
        normalizer = home + away
        return DiscreteDistribution(
            probabilities={
                "home": home / normalizer,
                "draw": 0.0,
                "away": away / normalizer,
            }
        )

    def diagnostics(self, game_context: Dict[str, Any]) -> Dict[str, Any]:
        probabilities, mean, covariance, home_wins = self._fit(game_context)
        home = float(probabilities[home_wins].sum())
        away = float(probabilities[~home_wins].sum())
        total_variance = float(covariance.sum())
        return {
            "conditional_on": "completed_standard_singles_match",
            "expected_games": {"home": float(mean[0]), "away": float(mean[1])},
            "game_covariance": covariance.tolist(),
            "total_games_variance": total_variance,
            "total_games_dispersion_index": total_variance / float(mean.sum()),
            "double_chance_probabilities": {
                "1X": home / (home + away),
                "X2": away / (home + away),
                "12": 1.0,
            },
            "historically_calibrated": False,
        }

    def value_contract(
        self,
        game_context: Dict[str, Any],
        selection: str,
        decimal_odds: float,
        void_probability: float = 0.0,
    ) -> Dict[str, Any]:
        """
        Evaluate a completed-match/void-refund contract.

        void_probability must be externally estimated for this contract.
        The forecast is conditional on nonvoid completion; no independence
        assumption is needed when that conditioning is respected.
        """
        odds = self._number(decimal_odds, "decimal_odds", positive=True)
        if odds < 1.0:
            raise ValueError("Decimal odds cannot be below one.")
        void = self._number(void_probability, "void_probability")
        if not 0.0 <= void <= 1.0:
            raise ValueError("void_probability must be in [0, 1].")
        if selection not in {"1X", "X2", "12"}:
            raise ValueError("selection must be 1X, X2, or 12.")

        forecast = self.diagnostics(game_context)["double_chance_probabilities"]
        conditional_win = forecast[selection]
        win = (1.0 - void) * conditional_win
        loss = (1.0 - void) * (1.0 - conditional_win)
        expected_profit = win * (odds - 1.0) - loss

        return {
            "selection": selection,
            "conditional_win_probability": conditional_win,
            "win_probability": win,
            "loss_probability": loss,
            "void_probability": void,
            "expected_profit_per_unit_stake": expected_profit,
            # 1.40 is the explicitly requested eligibility threshold.
            "eligible": odds >= 1.40 and expected_profit > 0.0,
        }