@dataclass
class ResearchQuestion:
    """A formal quantitative research inquiry generated by the AI Inquisitor."""
    question_id: str
    category: str  # 'alpha_acceleration' | 'market_microstructure' | 'situational_physics' | 'variance_reduction' | 'calibration'
    league: str
    segment: str
    title: str
    inquiry: str
    rationale: str
    potential_remedy_types: List[str] = field(default_factory=list)
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    status: str = "active"  # 'active' | 'brainstormed' | 'tested' | 'deployed'

    def to_dict(self) -> Dict[str, Any]:
        return {
            "question_id": self.question_id,
            "category": self.category,
            "league": self.league,
            "segment": self.segment,
            "title": self.title,
            "inquiry": self.inquiry,
            "rationale": self.rationale,
            "potential_remedy_types": self.potential_remedy_types,
            "created_at": self.created_at,
            "status": self.status,
        }


