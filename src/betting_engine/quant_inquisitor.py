def log_brainstorming_session(
    question: ResearchQuestion,
    hypotheses_generated: List[ResearchRecord],
    crucible_results: List[Dict[str, Any]],
    output_path: Path = BRAINSTORMING_SESSIONS_PATH
) -> None:
    """Logs the multi-AI brainstorming session to durable research audit lines."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    session_record = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "question": question.to_dict(),
        "hypotheses_count": len(hypotheses_generated),
        "hypotheses": [h.to_dict() for h in hypotheses_generated],
        "crucible_evaluations": crucible_results,
    }
    with open(output_path, "a", encoding="utf-8") as f:
        f.write(json.dumps(session_record) + "\n")


def run_continuous_inquisitor_cycle(
    conn: sqlite3.Connection,
    journal: Optional[HypothesisJournal] = None,
    limit: int = 3
) -> Dict[str, Any]:
    """Executes a proactive brainstorming cycle:
    1. Selects active research questions from the curriculum.
    2. Brainstorms testable mathematical hypotheses.
    3. Runs walk-forward crucible backtests on historical out-of-time data.
    4. Enqueues approved candidates into shadow observation in hypotheses_journal.json.
    5. Logs the brainstorming trajectory to durable audit files.
    """
    if journal is None:
        journal = HypothesisJournal()

    curriculum = get_proactive_research_curriculum(conn)
    tested_questions = 0
    hypotheses_produced = 0
    crucible_evals = []

    for q in curriculum[:limit]:
        tested_questions += 1
        candidates = brainstorm_hypotheses_from_question(q)
        q_crucible_evals = []

        for hyp in candidates:
            # Check if previously recorded to prevent duplicate crucible runs
            existing = journal.load().get("records", {}).get(hyp.hypothesis_id)
            if existing and existing.get("status") in ("deployed", "validated"):
                continue

            hypotheses_produced += 1
            # Run walk-forward crucible backtest
            res = run_crucible_walk_forward(hyp, conn)
            eval_dict = res.to_dict()
            q_crucible_evals.append(eval_dict)

            # Assign shadow status
            if res.passed and res.brier_improvement > 0:
                hyp.status = "validated"
                hyp.notes = [f"Passed walk-forward crucible: ΔBrier {res.brier_improvement:+0.4f}, ΔROI {res.roi_delta_pct:+.2f}%"]
            else:
                hyp.status = "in_shadow"
                hyp.notes = [f"Enqueued in shadow observation. Sample: {res.sample_size}, ΔBrier {res.brier_improvement:+0.4f}"]

            hyp.best_brier_improvement = res.brier_improvement
            hyp.best_simulated_roi_delta = res.roi_delta_pct
            hyp.crucible_evidence = eval_dict

            # Save in journal
            data = journal.load()
            data["records"][hyp.hypothesis_id] = hyp.to_dict()
            journal.save(data)

        q.status = "brainstormed"
        log_brainstorming_session(q, candidates, q_crucible_evals)
        crucible_evals.extend(q_crucible_evals)

    return {
        "status": "success",
        "executed_at": datetime.now(timezone.utc).isoformat(),
        "questions_inquired": tested_questions,
        "hypotheses_brainstormed": hypotheses_produced,
        "crucible_evaluations": len(crucible_evals),
    }
