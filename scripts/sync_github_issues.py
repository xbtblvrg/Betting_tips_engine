#!/usr/bin/env python3
"""Synchronizes system research gaps, demoted market turnarounds, and Crucible graduations with GitHub Issues."""
from __future__ import annotations

import json
import sqlite3
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = "xbtblvrg/Betting_tips_engine"


def run_cmd(args: list[str]) -> str:
    res = subprocess.run(args, capture_output=True, text=True, cwd=ROOT)
    if res.returncode != 0:
        raise RuntimeError(f"Command failed ({' '.join(args)}): {res.stderr.strip()}")
    return res.stdout.strip()


def get_existing_issues() -> dict[str, dict]:
    try:
        raw = run_cmd(["gh", "issue", "list", "--repo", REPO, "--state", "all", "--json", "number,title,state,labels", "--limit", "100"])
        issues = json.loads(raw) if raw else []
        return {i["title"]: i for i in issues}
    except Exception as e:
        print(f"Warning: Could not fetch existing GitHub issues: {e}")
        return {}


def create_issue(title: str, body: str, labels: list[str]) -> None:
    print(f"Creating Issue: {title} (labels: {labels})")
    cmd = ["gh", "issue", "create", "--repo", REPO, "--title", title, "--body", body]
    for lbl in labels:
        cmd.extend(["--label", lbl])
    out = run_cmd(cmd)
    print(f"Created: {out}")


def comment_and_close_issue(issue_number: int, comment: str) -> None:
    print(f"Closing Issue #{issue_number} with comment...")
    run_cmd(["gh", "issue", "comment", str(issue_number), "--repo", REPO, "--body", comment])
    run_cmd(["gh", "issue", "close", str(issue_number), "--repo", REPO, "--reason", "completed"])


def sync_research_gaps(existing: dict[str, dict]) -> None:
    """Syncs unfulfilled model research gaps from engine.sqlite3."""
    db_path = ROOT / "data" / "engine.sqlite3"
    if not db_path.exists():
        return
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()
    cur.execute("SELECT league, payload, result FROM learning_jobs WHERE status = 'needs_implementation' AND kind = 'research_gap'")
    rows = cur.fetchall()
    conn.close()

    by_league: dict[str, list[dict]] = {}
    for league, pl_raw, res_raw in rows:
        lg = league or "GLOBAL"
        pl = json.loads(pl_raw) if pl_raw else {}
        by_league.setdefault(lg, []).append(pl)

    for lg, tasks in by_league.items():
        title = f"[RESEARCH GAP] {lg}: Independent Domain Model & Derivative Validation"
        if title in existing:
            continue
        body = (
            f"## Research Gap: {lg}\n\n"
            f"The Autonomous Quant Engine identified observed contracts in **{lg}** that require "
            f"independent domain models before real-money recommendations can be published (Commandment 3: Pure Independent Models).\n\n"
            f"### Logged Tasks:\n"
        )
        for t in tasks:
            body += f"- **Task:** {t.get('task', 'Model formulation')}\n  - **Reason:** {t.get('reason', 'Missing independent distribution')}\n"
        body += "\n---\n*Auto-generated by `scripts/sync_github_issues.py` from `learning_jobs`.*"
        create_issue(title, body, ["research-gap"])


    # Check for resolved research gaps to close
    for title, issue_meta in existing.items():
        if issue_meta.get("state") == "OPEN" and title.startswith("[RESEARCH GAP]"):
            # Extract league
            try:
                lg = title.split("[RESEARCH GAP]")[1].split(":")[0].strip()
                if lg not in by_league:
                    comment_and_close_issue(
                        issue_meta["number"],
                        f"All identified independent model gaps for **{lg}** have been implemented or validated. Closing issue."
                    )
            except Exception:
                pass


def sync_demoted_turnarounds(existing: dict[str, dict]) -> None:
    """Syncs deteriorating markets in $0.00 Capital Defense quarantine to GitHub Issues by sport/league."""
    inc_db = ROOT / "data" / "shadow_incubator.sqlite3"
    if not inc_db.exists():
        return
    conn = sqlite3.connect(inc_db)
    cur = conn.cursor()
    cur.execute("SELECT league, scope, segment_key, rolling_roi, rolling_pnl, games, reason FROM demoted_markets ORDER BY rolling_pnl ASC")
    rows = cur.fetchall()
    conn.close()

    by_league: dict[str, list[tuple]] = {}
    for lg, sc, seg_k, roi, pnl, games, reason in rows:
        by_league.setdefault(lg, []).append((sc, seg_k, roi, pnl, games, reason))

    for lg, segs in by_league.items():
        title = f"[CAPITAL DEFENSE] Multi-AI Turnaround: {lg} Quarantine ({len(segs)} segments)"
        if title in existing:
            continue
        body = (
            f"## Capital Defense & Incubator Turnaround: {lg}\n\n"
            f"In accordance with **Constitutional Commandments 6 & 7** (Demoted Market Quarantine & Law of Market Preservation), "
            f"the following {len(segs)} segments in **{lg}** experienced live drawdown and are **strictly quarantined at $0.00 virtual stakes**.\n\n"
            f"They remain active in the **Shadow Incubator** tracking live odds until passing the **Walk-Forward Crucible** backtest.\n\n"
            f"### Quarantined Segments:\n"
            f"| Segment Key | Scope | Rolling ROI | Rolling PnL | Live Games |\n"
            f"| :--- | :--- | :--- | :--- | :--- |\n"
        )
        for sc, seg_k, roi, pnl, games, reason in segs[:15]:
            body += f"| `{seg_k}` | `{sc}` | `{roi*100:.1f}%` | `${pnl:.2f}` | `{games}` |\n"
        if len(segs) > 15:
            body += f"\n*...and {len(segs) - 15} more derivative submarkets in this league.*"
        body += (
            f"\n\n### Mandatory Turnaround Protocol (3D Expansion):\n"
            f"- **Dimension A (Data):** Integrate starting lineup / wind / goalie data.\n"
            f"- **Dimension B (Portfolio Shield):** Tighten EV hurdles (+3.5%) and calibrate shrinkage curves.\n"
            f"- **Crucible Re-Graduation Gate:** Simulated ROI >= +3.0%, Brier improvement > 0.001 over 25+ shadow games.\n\n"
            f"---\n*Auto-generated by `scripts/sync_github_issues.py` from `shadow_incubator.sqlite3`.*"
        )
        create_issue(title, body, ["capital-defense", "quant-council"])

    # Check for fully graduated leagues to close
    for title, issue_meta in existing.items():
        if issue_meta.get("state") == "OPEN" and title.startswith("[CAPITAL DEFENSE]"):
            try:
                lg = title.split("Multi-AI Turnaround:")[1].split("Quarantine")[0].strip()
                if lg not in by_league:
                    comment_and_close_issue(
                        issue_meta["number"],
                        f"All quarantined segments in **{lg}** have successfully passed Crucible validation and re-graduated to active funded trading! 0 segments remaining in quarantine. Closing issue."
                    )
            except Exception:
                pass


def main():
    print("=== GitHub Issues Synchronizer ===")
    existing = get_existing_issues()
    print(f"Loaded {len(existing)} existing GitHub issues.")
    sync_research_gaps(existing)
    sync_demoted_turnarounds(existing)
    print("=== Issues sync completed! ===")


if __name__ == "__main__":
    main()
